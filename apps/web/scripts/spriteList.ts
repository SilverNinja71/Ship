// Writes docs/sprite-list.md: every sprite Ship can use, with its size and
// anchor, plus each ship's reference spots so hull art lines up with the
// deck. Generated from the theme kit's sheet specs and the built-in layouts,
// so it can't drift from the code (the assets test checks it's current).

import { SHIP_DEFAULT_PLACEMENTS } from "@ship/shared-types";
import { HULL_SPRITE, RIGGING_SPRITE, SHIPS, spriteSheetSpecs } from "@ship/ship-theme-kit";
import type { SpriteSheetSpec } from "@ship/ship-theme-kit";
import { hullDrawer } from "../src/ships/index.js";

const pt = (p: { x: number; y: number }) => `(${Math.round(p.x)}, ${Math.round(p.y)})`;
const hullPx = (p: { x: number; y: number }) => `(${Math.round(p.x + HULL_SPRITE.anchor.x)}, ${Math.round(p.y + HULL_SPRITE.anchor.y)})`;

function sheetTable(spec: SpriteSheetSpec): string[] {
  const rows = spec.sprites.map((s) => `| \`${s.id}\` | ${s.width} × ${s.height} | (${s.anchor.x}, ${s.anchor.y}) | ${s.tintable ? "yes" : ""} | ${s.group} | ${s.note} |`);
  return [`| id | size | anchor | greys | part | what |`, `|---|---|---|---|---|---|`, ...rows];
}

function shipSpots(shipId: string): string[] {
  const ship = SHIPS.find((s) => s.id === shipId)!;
  // The built-in layout, before any manifest overrides: what the art should match.
  const l = hullDrawer(ship).layout(ship);
  const rows: [string, string, string][] = [
    ["main deck", `x ${l.deck.from} to ${l.deck.to}, y 0`, `columns ${l.deck.from + 500}–${l.deck.to + 500}, row 150`],
    ...(l.surfaces ?? []).filter((s) => s.y !== 0).map((s): [string, string, string] => ["raised deck", `x ${s.from} to ${s.to}, y ${s.y}`, `columns ${s.from + 500}–${s.to + 500}, row ${s.y + 150}`]),
    ["waterline", `y ${l.waterline}`, `row ${l.waterline + 150}`],
    ...l.masts.map((m, i): [string, string, string] => [`mast ${i + 1}`, `x ${m.x}, from y ${m.base} up to ${m.top}`, `rigging column ${m.x + RIGGING_SPRITE.anchor.x}, rows ${m.top + RIGGING_SPRITE.anchor.y}–${m.base + RIGGING_SPRITE.anchor.y}`]),
    ["figurehead mount", `${pt(l.bow)}, facing ${Math.round((l.bow.angle * 180) / Math.PI)}°`, hullPx(l.bow)],
    ["flag pole top", pt(l.flag), `rigging ${`(${l.flag.x + RIGGING_SPRITE.anchor.x}, ${l.flag.y + RIGGING_SPRITE.anchor.y})`}`],
    ["helm", pt(l.helm), hullPx(l.helm)],
    ["citrus tree", pt(l.citrusTree), hullPx(l.citrusTree)],
    ...l.orchard.map((o): [string, string, string] => ["orchard tree", pt(o), hullPx(o)]),
    ["bell (hangs from)", pt(l.bell), "rigging or hull-back"],
    ["your desk", pt(l.desk), hullPx(l.desk)],
    ...l.tables.map((t, i): [string, string, string] => [`crew table ${i + 1}`, pt(t), hullPx(t)]),
    ...l.smoke.map((s): [string, string, string] => ["chimney top (smoke)", pt(s), "rigging or hull-back"]),
  ];
  return ["| spot | ship units | in the art |", "|---|---|---|", ...rows.map(([a, b, c]) => `| ${a} | ${b} | ${c} |`)];
}

export function spriteListMarkdown(): string {
  const specs = spriteSheetSpecs();
  const out: string[] = [
    "<!-- Generated by `npm run assets -w @ship/web` from the theme kit and the ship layouts. Don't edit by hand. -->",
    "",
    "# Ship sprite list",
    "",
    "Every sprite Ship can use. Read [art-brief.md](art-brief.md) first. Sizes and anchors are in pixels at density 1;",
    "art delivered at double size sets `\"density\": 2` and doubles every number. \"greys\" means draw it in greys",
    "and set `\"tintable\": true`. Sprites in the same \"part\" are used together, once all of them exist.",
    "",
  ];
  const shared = specs.filter((s) => s.kind !== "ship" && s.kind !== "environment");
  for (const spec of shared) out.push(`## ${spec.title}: \`assets/${spec.folder}/\``, "", ...sheetTable(spec), "");

  const envs = specs.filter((s) => s.kind === "environment");
  out.push("## Environments: `assets/environment/<environment>/`", "", `One folder per environment: ${envs.map((e) => `\`${e.folder.split("/")[1]}\` (${e.title})`).join(", ")}.`, "", ...sheetTable(envs[0]), "");

  const ships = specs.filter((s) => s.kind === "ship");
  out.push(
    "## Ships: `assets/ships/<ship>/`",
    "",
    "Every ship folder holds the same pieces:",
    "",
    ...sheetTable(ships[0]),
    "",
    `Without \`placements\` in the manifest, the pieces go at ${SHIP_DEFAULT_PLACEMENTS.map((p) => `\`${p.sprite}\` (${p.x}, ${p.y}) z ${p.zIndex}`).join(", ")}.`,
    "Extra pieces (a bowsprit, wings, a leviathan) are listed as sprites and placed with `placements`.",
    "",
    "Each ship below lists where the engine puts things on the built-in layout. Ship units have the main deck at y 0 and the",
    `ship's middle at x 0 (stern left, bow right, y down). In the hull images that is column x + ${HULL_SPRITE.anchor.x}, row y + ${HULL_SPRITE.anchor.y};`,
    `in the rigging image, column x + ${RIGGING_SPRITE.anchor.x}, row y + ${RIGGING_SPRITE.anchor.y}. Draw decks where the spots are, or put your own spots in the`,
    "manifest's `layout` (in ship units). The hull below about 30 units under the waterline is hidden by the front waves.",
    "",
  );
  for (const spec of ships) out.push(`### ${spec.title} (\`${spec.folder}\`)`, "", ...shipSpots(spec.folder.split("/")[1]), "");
  return out.join("\n");
}
