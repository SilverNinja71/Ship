const byId = new Map(SHIPS.map((s) => [s.id, s]));

export function getShip(id: string): ShipDefinition | undefined {
  return byId.get(id);
}

/** Like getShip, but falls back to the starter ship so callers always get something drawable. */
export function shipOrStarter(id: string): ShipDefinition {
  return byId.get(id) ?? byId.get(STARTER_SHIP_ID)!;
}

export function shipsInCategory(category: ShipCategory): ShipDefinition[] {
  return SHIPS.filter((s) => s.category === category);
}
